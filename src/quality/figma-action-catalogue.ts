export const FIGMA_ACTION_CATALOGUE_TARGET = 100;
export function summarizeActionCatalogue() {
  const counts = { implemented: 0, partial: 0, planned: 0, unsupported: 0 };
  FIGMA_ACTION_CATALOGUE.forEach((item) => { counts[item.readiness] += 1; });
  return {
    total: FIGMA_ACTION_CATALOGUE.length,
    target: FIGMA_ACTION_CATALOGUE_TARGET,
    targetMet: FIGMA_ACTION_CATALOGUE.length >= FIGMA_ACTION_CATALOGUE_TARGET,
    counts,
    categories: [...new Set(FIGMA_ACTION_CATALOGUE.map((item) => item.category))],
  };
}
